package dev.ghostmap.fixtures.hauntedhouse;

import lombok.RequiredArgsConstructor;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Repository;

import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.List;
import java.util.Optional;

@Repository
@RequiredArgsConstructor
public class JdbcSpiritRepository implements SpiritRepository {
    private final JdbcTemplate jdbcTemplate;

    @Override
    public void reset() {
        jdbcTemplate.execute("drop table if exists spirits");
        jdbcTemplate.execute("create table spirits (id bigint generated by default as identity primary key, "
                + "name varchar(100) not null)");
    }

    @Override
    public void save(Spirit spirit) {
        jdbcTemplate.update("insert into spirits(name) values (?)", spirit.getName());
    }

    @Override
    public Optional<Spirit> findByName(String name) {
        List<Spirit> matches = jdbcTemplate.query(
                "select id, name from spirits where name = ?", this::mapSpirit, name);
        return matches.stream().findFirst();
    }

    @Override
    public int count() {
        Integer count = jdbcTemplate.queryForObject("select count(*) from spirits", Integer.class);
        return count == null ? 0 : count;
    }

    private Spirit mapSpirit(ResultSet resultSet, int rowNumber) throws SQLException {
        Spirit spirit = new Spirit();
        spirit.setId(resultSet.getLong("id"));
        spirit.setName(resultSet.getString("name"));
        return spirit;
    }
}
